#include <iostream>
using namespace std;

int main()
{
    int age = 19;
    char grade = 'A';
    float PI = 3.14;
    bool isSafe = false;
    double price = 100.99;

    cout << "Age is : " << age << endl;
    cout << "Grade is : " << grade << endl;
    cout << "PI is : " << PI << endl;
    cout << "isSfae =  " << isSafe << endl;
    cout << "Price is : " << price << endl;
    return 0;
}


