#include <iostream>
using namespace std;

int main()
{
    cout << (3<5) << endl;
    cout << (3>5) << endl;
    cout << (3<=3) << endl;
    cout << (3==3) << endl;
    cout << (5==3) << endl;
    cout << (5!=3) << endl;
    cout << (3!=3) << endl;
    

    /*
        Relational Operators:-
        <
        <=
        >
        >=
        ==
        !=

        -Returns true(1) or false(0) only.
    */
    return 0;
}